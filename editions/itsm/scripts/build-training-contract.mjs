import {readFileSync,writeFileSync} from 'node:fs';
const source=readFileSync(new URL('../content/training-contract-v1.json',import.meta.url),'utf8');
// No browser JSON fetch, network access, or server-private role facts are needed.
const generated=`// Generated by scripts/build-training-contract.mjs. Edit content/training-contract-v1.json, not this file.\nexport const trainingContractData = ${source.trim()};\n`;
const destination=new URL('../public/training-contract-data.js',import.meta.url);
if(process.argv.includes('--check')){
 if(readFileSync(destination,'utf8')!==generated)throw new Error('Training contract browser data drift: run node scripts/build-training-contract.mjs.');
 console.log('Training contract source and browser data match.');
}else{writeFileSync(destination,generated);console.log('Training contract browser data generated.');}
